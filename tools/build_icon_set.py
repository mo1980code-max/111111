def brand_mark(name, size, viewport, stroke, dot_radius):
    """The original brand symbol: a circle of remembrance, an eight-point geometric star built
    from two rotated squares, and a still centre point."""
    c = viewport / 2.0
    r = viewport * 0.40
    half = r * 0.70
    sq1 = (f"M{c - half:.2f},{c - half:.2f} H{c + half:.2f} V{c + half:.2f} "
           f"H{c - half:.2f} Z")
    d = r * 0.99
    sq2 = (f"M{c:.2f},{c - d:.2f} L{c + d:.2f},{c:.2f} L{c:.2f},{c + d:.2f} "
           f"L{c - d:.2f},{c:.2f} Z")
    paths = [
        s(f"M{c:.2f},{c - r:.2f} a{r:.2f},{r:.2f} 0 1,0 0.01,0 Z", stroke),
        s(sq1, stroke),
        s(sq2, stroke),
        dot(c, c, dot_radius),
    ]
    vector(name, paths, size=size, viewport=viewport)


