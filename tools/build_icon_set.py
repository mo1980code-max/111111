def vector(name, paths, size=24.0, viewport=24.0, auto_mirrored=False, tint_attr=True):
    lines = [HEADER.rstrip("\n"), '<vector xmlns:android="http://schemas.android.com/apk/res/android"']
    lines.append(f'    android:width="{size:g}dp"')
    lines.append(f'    android:height="{size:g}dp"')
    lines.append(f'    android:viewportWidth="{viewport:g}"')
    lines.append(f'    android:viewportHeight="{viewport:g}"')
    if auto_mirrored:
        lines.append('    android:autoMirrored="true"')
    lines.append(f'    android:tint="{INK}">')
    for path in paths:
        data = path["d"]
        if path.get("fill"):
            lines.append("    <path")
            lines.append(f'        android:fillColor="#FF000000"')
            lines.append(f'        android:pathData="{data}" />')
        else:
            width = path.get("w", STROKE)
            lines.append("    <path")
            lines.append('        android:fillColor="#00000000"')
            lines.append('        android:strokeColor="#FF000000"')
            lines.append(f'        android:strokeWidth="{width:g}"')
            lines.append('        android:strokeLineCap="round"')
            lines.append('        android:strokeLineJoin="round"')
            lines.append(f'        android:pathData="{data}" />')
    lines.append("</vector>")
    (DRAWABLE / f"{name}.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def s(d, w=STROKE):
    return {"d": d, "w": w}


def f(d):
    return {"d": d, "fill": True}


def dot(cx, cy, r):
    return f(f"M{cx:g},{round(cy - r, 2):g} a{r:g},{r:g} 0 1,0 0.01,0 Z")


def circle(cx, cy, r, w=STROKE):
    return s(f"M{cx},{cy - r} a{r},{r} 0 1,0 0.01,0 Z", w)


